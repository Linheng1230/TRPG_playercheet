import json,os,re
from pathlib import Path
from opencc import OpenCC
repo=Path(__file__).resolve().parents[1]
root=Path(os.environ.get("FIVERTOOLS_ROOT",r"D:\Tools\zizi-ai-runtime\trpg-playercheet-qa\5rtools-2024"))
cc=OpenCC("s2twp")
def load(name): return json.loads((root/name).read_text(encoding="utf-8-sig"))
def zh(x): return cc.convert(str(x.get("name") or ""))
def slug(s):
 s=str(s or "").lower().replace("’","").replace("'","")
 return re.sub(r"(^-+|-+$)","",re.sub(r"[^a-z0-9]+","-",s))
out={"source":"5RTools PHB2024 fixed snapshot","spells":{},"feats":{},"optionalFeatures":{},"races":{},"backgrounds":{},"skills":{},"items":{},"classes":{},"subclasses":{},"classFeatures":{},"subclassFeatures":{}}
for x in load("data__spells__spells-phb2024.json").get("spell",[]):
 if x.get("source")=="PHB2024": out["spells"][x["ENG_name"]]=zh(x)
for x in load("data__feats.json").get("feat",[]):
 if x.get("source")=="PHB2024": out["feats"][slug(x["ENG_name"])]={"en":x["ENG_name"],"zh":zh(x)}
for x in load("data__optionalfeatures.json").get("optionalfeature",[]):
 if x.get("source")=="PHB2024": out["optionalFeatures"][x["ENG_name"]]={"zh":zh(x),"featureType":x.get("featureType",[])}
for x in load("data__races.json").get("race",[]):
 if x.get("source")=="PHB2024": out["races"][x["ENG_name"]]=zh(x)
background_data=load("data__backgrounds.json")
background_rows=[x for x in background_data.get("background",[]) if x.get("source")=="PHB2024"]
for x in background_rows: out["backgrounds"][x["ENG_name"]]=zh(x)
skill_tags=sorted(set(re.findall(r"\{@skill\s+([^}|]+)",json.dumps(background_rows,ensure_ascii=False))))
for raw in skill_tags: out["skills"][raw]=cc.convert(raw)
for x in load("data__items-base.json").get("baseitem",[]):
 if x.get("source")=="PHB2024" and x.get("ENG_name"): out["items"][x["ENG_name"]]={"zh":zh(x),"type":x.get("type")}
for f in sorted(root.glob("data__class__class-*.json")):
 d=json.loads(f.read_text(encoding="utf-8-sig"))
 for x in d.get("class",[]):
  if x.get("source")=="PHB2024":
   out["classes"][x["ENG_name"]]=zh(x)
   for sc in x.get("subclasses",[]):
    if sc.get("source")=="PHB2024" and sc.get("ENG_name"):
     key=f'{x["ENG_name"]}|{sc["ENG_name"]}'; out["subclasses"][key]=zh(sc)
 for x in d.get("classFeature",[]):
  if x.get("source")=="PHB2024" or x.get("classSource")=="PHB2024":
   if x.get("ENG_name"):
    key=f'{x.get("className","")}|{x["ENG_name"]}|{x.get("level","")}'; out["classFeatures"][key]=zh(x)
 for x in d.get("subclassFeature",[]):
  if x.get("source")=="PHB2024" or x.get("classSource")=="PHB2024":
   if x.get("ENG_name"):
    key=f'{x.get("className","")}|{x.get("subclassShortName","")}|{x["ENG_name"]}|{x.get("level","")}'; out["subclassFeatures"][key]=zh(x)
js="/* Generated by scripts/build-5r-canonical-names.py from the fixed 5RTools PHB2024 snapshot. */\n"+"globalThis.ZIZI_5R_CANONICAL_NAMES="+json.dumps(out,ensure_ascii=False,separators=(",",":"))+";\n"
(repo/"assets/data/canonical-5r-zh-names.js").write_text(js,encoding="utf-8")
print(json.dumps({k:len(v) if isinstance(v,dict) else v for k,v in out.items()},ensure_ascii=False))
