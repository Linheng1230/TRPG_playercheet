"use strict";
const {chromium}=require("playwright"),assert=require("node:assert/strict");
const URL=process.env.QA_URL||"http://127.0.0.1:18766/index.html";
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  for(const width of [1440,480,390]){
   const page=await browser.newPage({viewport:{width,height:width===1440?900:844},isMobile:width===390,hasTouch:width===390,acceptDownloads:true});
   const errors=[];page.on("pageerror",e=>errors.push(e.message));
   await page.goto(URL,{waitUntil:"networkidle"});
   await page.evaluate(()=>{
    document.getElementById("rulesetModal")?.classList.remove("open");
    S.ruleset="2024";syncRulesetUI();S.cls=CLASSES.find(c=>c.n==="戰士");S.classLevels={戰士:1};S.level=1;
    S.gear.gold={pp:0,gp:1000,sp:0,cp:0};go(10);
   });
   await page.locator("[data-ss-toggle]").click();
   await page.locator("#ssNewTown").fill("霜港");
   await page.locator("#ssNewName").fill("晨星補給行");
   await page.locator("#ssNewTier").selectOption("metropolis");
   await page.locator("[data-ss-create]").click();
   const first=await page.evaluate(()=>window.ShopStores5R.selected());
   assert.equal(first.town,"霜港");assert.equal(first.name,"晨星補給行");
   assert.equal(first.tier,"metropolis");
   await page.locator("#ssSearch").fill("戰馬");
   await page.locator("#ssProducts").selectOption("mkt:戰馬");
   await page.locator("#ssStock").fill("1");
   await page.locator("#ssPrice").fill("120");
   await page.locator("[data-ss-item]").click();
   assert.equal(await page.locator('[data-buy="mkt:戰馬"]').count(),1);
   assert.equal(await page.locator('.ss-shop-stock').first().textContent(),"店內庫存：1 件");
   await page.locator('[data-buy="mkt:戰馬"]').click();
   let state=await page.evaluate(()=>({cp:moneyCp(),qty:S.gear.purchases["mkt:戰馬"],stock:ShopStores5R.offer(shopCatalog().find(x=>x.id==="mkt:戰馬")).stock,tx:S.gear.shopLedger.at(-1)}));
   assert.equal(state.cp,88000);assert.equal(state.qty,1);assert.equal(state.stock,0);
   assert.equal(state.tx.cp,12000);assert.equal(state.tx.shopId,first.id);
   assert(await page.locator('[data-buy="mkt:戰馬"]').isDisabled(),"Sold-out shop should block purchase");
   await page.locator('[data-ss-pick="mkt:戰馬"]').click();
   await page.locator("#ssPrice").fill("80");
   await page.locator("[data-ss-item]").click();
   await page.locator('[data-refund="mkt:戰馬"]').click();
   state=await page.evaluate(()=>({cp:moneyCp(),purchases:S.gear.purchases["mkt:戰馬"]||0,stock:ShopStores5R.offer(shopCatalog().find(x=>x.id==="mkt:戰馬")).stock}));
   assert.deepEqual(state,{cp:100000,purchases:0,stock:1},"Refund must use original 120 GP even after repricing to 80 GP");
   await page.locator("#ssSearch").fill("Potion of Healing");
   await page.locator("#ssProducts").selectOption("magic:potion-of-healing|xdmg");
   await page.locator("#ssStock").fill("2");await page.locator("#ssPrice").fill("75");
   await page.locator("[data-ss-item]").click();
   page.once("dialog",d=>d.accept());
   await page.locator('[data-buy="magic:potion-of-healing|xdmg"]').click();
   state=await page.evaluate(()=>({cp:moneyCp(),qty:S.gear.magicItems.find(x=>x.id==="potion-of-healing|xdmg")?.qty||0,stock:ShopStores5R.offer(shopCatalog().find(x=>x.id==="magic:potion-of-healing|xdmg")).stock}));
   assert.deepEqual(state,{cp:92500,qty:1,stock:1});
   const charSave=await page.evaluate(()=>serialize());
   assert.equal(charSave.gear.shopLedger.length,1);
   await page.evaluate(save=>deserialize(save),charSave);
   assert.equal(await page.evaluate(()=>S.gear.magicItems.find(x=>x.id==="potion-of-healing|xdmg")?.qty),1);
   await page.reload({waitUntil:"networkidle"});
   await page.evaluate(()=>{document.getElementById("rulesetModal")?.classList.remove("open");go(10)});
   assert.equal(await page.locator("#ssSelect option").count(),2);
   assert.equal(await page.locator("#ssSelect").inputValue(),first.id);
   await page.locator("[data-ss-toggle]").click();
   await page.locator("#ssNewTown").fill("霜港");
   await page.locator("#ssNewName").fill("北門工坊");
   await page.locator("[data-ss-create]").click();
   const second=await page.evaluate(()=>ShopStores5R.selected().id);assert.notEqual(second,first.id);
   assert.equal(await page.locator('[data-buy="mkt:戰馬"]').count(),0,"Second store must have separate inventory");
   await page.locator("#ssSelect").selectOption(first.id);
   assert.equal(await page.locator('[data-buy="mkt:戰馬"]').count(),1);
   const downloadPromise=page.waitForEvent("download");
   await page.locator("[data-ss-export]").click();
   const download=await downloadPromise;assert(download.suggestedFilename().endsWith(".json"));
   await page.locator("#ssSelect").selectOption("");
   assert.equal(await page.locator("[data-shop-tier]").count(),5,"Legacy settlement browsing must remain available");
   assert.equal(await page.locator(".ss-panel").count(),1);
   const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);
   assert(overflow<=2,"Horizontal overflow "+overflow+" on width "+width);
   assert.deepEqual(errors,[]);
   console.log(JSON.stringify({pass:true,width,priceChangeRefund:true,stockRestock:true,magic:true,shopIsolation:true,save:true,export:true,overflow}));
   await page.close();
  }
 }finally{await browser.close()}
})().catch(e=>{console.error(e.stack||e);process.exit(1)});
