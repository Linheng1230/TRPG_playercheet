const assert=require("node:assert/strict");
const L=require("../assets/session-ledger-5r.js");
let d=L.create({characterId:"char1",sessionId:"session1",mode:"free"});
const event={eventId:"evt1",sessionId:"session1",characterId:"char1",createdAt:"2026-11-13T00:00:00Z",type:"currency_gain",payload:{amount:50,currency:"GP"}};
d=L.add(d,event);
assert.equal(d.events.length,1);
assert.equal(L.add(d,event).events.length,1,"idempotent event");
assert.throws(()=>L.add(d,{...event,payload:{amount:500}}),/Conflicting/);
assert.deepEqual(L.importJSON(L.exportJSON(d)),d,"JSON roundtrip");
assert.equal(L.merge(d,L.importJSON(L.exportJSON(d))).events.length,1,"idempotent merge");
assert.throws(()=>L.importJSON('{"schemaVersion":1}'),/格式不正確/);
assert.throws(()=>L.importJSON('{broken'),SyntaxError);
assert.throws(()=>L.add(d,{...event,eventId:"evt2",characterId:"another"}),/ownership/);
assert.throws(()=>L.merge(d,L.create({characterId:"char1",sessionId:"session1",mode:"al"})),/Different/);
const reviewed=L.setSettlement(d,{status:"approved",trust:"local-unverified"});
assert.throws(()=>L.add(reviewed,{...event,eventId:"evt2"}),/locked/);
assert.throws(()=>L.setSettlement(reviewed,{status:"approved",trust:"local-unverified",extra:1}),/already exists/);
const al=L.create({characterId:"char2",sessionId:"session2",mode:"al"});
assert.throws(()=>L.setSettlement(al,{status:"approved",trust:"local-unverified"}),/server verification/);
assert.throws(()=>L.importJSON(JSON.stringify({...d,events:[event,event]})),/Duplicate/);
const zh=L.create({characterId:"奈瑟林",sessionId:"冰封之病 11-13",mode:"free"});
assert.deepEqual(L.importJSON(L.exportJSON(zh)),zh,"Chinese names round-trip");
assert.throws(()=>L.create({characterId:"奈瑟林",sessionId:"不合法/場次"}),/格式不正確/);
console.log("PASS session ledger: 15 assertions including Chinese names and negative cases");
