/* Targeted warlock familiar tests, no browser dependencies. */
const fs=require("fs"),vm=require("vm"),assert=require("assert"),path=require("path");
const root=path.resolve(__dirname,"..");
const doc={events:{},createElement:()=>({textContent:""}),head:{appendChild(){}},addEventListener(type,cb){this.events[type]=cb}};
const ctx={document:doc,window:{},console,confirm:()=>true};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root,"assets/data/creatures-5r.js"),"utf8"),ctx);
vm.runInContext(fs.readFileSync(path.join(root,"assets/data/creatures-5r-zh.js"),"utf8"),ctx);
vm.runInContext(fs.readFileSync(path.join(root,"assets/warlock-familiar-5r.js"),"utf8"),ctx);
const wf=ctx.window.WarlockFamiliar;
const owl=ctx.window.ZIZI_5R_CREATURES.find(x=>x.name==="Owl");
const imp=ctx.window.ZIZI_5R_CREATURES.find(x=>x.name==="Imp");
assert(owl&&imp,"canonical owl and imp exist");
ctx.validInvocationsSet2024=()=>new Set();
const s={ruleset:"2024",cls:{n:"邪術師"},familiar:null};
assert(!wf.permission(s),"warlock without Pact of Chain cannot use specials");
assert(wf.eligible(owl,false),"normal owl is eligible");
assert(!wf.eligible(imp,false),"special imp unavailable without Pact of Chain");
assert(!wf.candidates(false).some(x=>x.name==="Imp"),"no special candidates for Tome");
ctx.validInvocationsSet2024=()=>new Set(["鎖鏈之契"]);
assert(wf.permission(s),"chain invocation unlocks special form");
assert(wf.eligible(imp,true),"imp eligible with chain");
assert(["Imp","Pseudodragon","Quasit","Skeleton","Slaad Tadpole","Sphinx of Wonder","Sprite","Venomous Snake"].every(name=>wf.candidates(true).some(x=>x.name===name)),"all eight special forms available");
assert(!wf.hasInvestment(s),"investment not automatic");
ctx.validInvocationsSet2024=()=>new Set(["鎖鏈之契","鎖鏈大師之資"]);
assert(wf.hasInvestment(s),"investment only when selected");
s.familiar={creatureId:owl.id,nickname:"小羽",spirit:"fey",notes:"偵查",status:"present"};
const save=JSON.parse(JSON.stringify(s.familiar));
assert.deepStrictEqual(JSON.parse(JSON.stringify(wf.normalize(save))),save,"JSON round trip");
assert.strictEqual(wf.normalize({creatureId:"invalid"}),null,"unknown creature rejected");
assert.strictEqual(wf.normalize(null),null,"old save absent familiar valid");
assert(!wf.permission({...s,ruleset:"2014"}),"2014 feature branch isolated");
assert(!wf.permission({...s,cls:{n:"法師"}}),"other class cannot gain chain");
const html=wf.render(s);
assert(html.includes("小羽")&&html.includes("100 呎")&&html.includes("鎖鏈大師之資"),"rendered bilingual familiar and mechanics");
assert(!html.includes("data-wf-choose=\"not-present\""),"no nonexistent creature");
console.log("PASS qa-warlock-familiar: permission, 8 options, investment, owl, legacy, JSON, 2014 isolation, render");
