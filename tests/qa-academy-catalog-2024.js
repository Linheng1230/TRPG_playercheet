"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const cp=require("node:child_process");
const root=path.resolve(__dirname,"..");
cp.execFileSync(process.execPath,[path.join(root,"scripts/build-academy-catalog-2024.js"),"--check"],{stdio:"pipe"});
const source=fs.readFileSync(path.join(root,"assets/data/academy-catalog-2024.js"),"utf8");
const browser={};browser.globalThis=browser;
vm.runInNewContext(source,browser,{timeout:1000});
const catalog=browser.DND5RAcademyCatalog2024;
const quiz=require("../assets/class-fit-quiz-5r.js");
assert.equal(catalog.edition,"2024");
assert.equal(catalog.classes.length,12);
assert.equal(Object.values(catalog.progression).reduce((n,x)=>n+x.subs.length,0),48);
assert.equal(catalog.backgrounds.length,16);
assert.equal(catalog.species.length,10);
assert.match(catalog.sourceSha256,/^[a-f0-9]{64}$/);
assert.ok(catalog.backgrounds.every(b=>Array.isArray(b.ab)&&b.ab.length>0&&b.feat));
const fighter=quiz.evaluate("A A A A D A A A A A".split(" "),catalog);
if(fighter.status!=="READY")console.log("diagnostic",fighter.warnings,fighter.recommendations.map(r=>({className:r.className,subclass:!!r.subclass,background:!!r.background,species:!!r.species})));
assert.equal(fighter.status,"READY");
assert.equal(fighter.recommendations.length,3);
assert.equal(fighter.recommendations[0].className,"戰士");
assert.ok(fighter.recommendations.every(r=>r.subclass&&r.background&&r.species));
assert.ok(fighter.recommendations.every(r=>r.prefill.confirmed===false));
console.log("PASS derived academy catalog: 12 classes / 48 subclasses / 16 backgrounds / 10 species; real 3-card quiz / no confirmation");
