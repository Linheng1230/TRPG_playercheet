"use strict";
const assert = require("assert");
const {chromium} = require("playwright");
const URL = process.env.QA_URL || "http://127.0.0.1:18766/index.html";
const CHAIN = ["Imp","Pseudodragon","Quasit","Skeleton","Slaad Tadpole","Sphinx of Wonder","Sprite","Venomous Snake"];
(async () => {
 let browser;
 try {
  browser = await chromium.launch({headless:true,channel:"chrome"});
  const page = await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  await page.goto(URL+"?qa=familiar-categories",{waitUntil:"networkidle"});
  if(await page.locator("#closeRuleset").isVisible())await page.locator("#closeRuleset").click();
  await page.evaluate(()=>go(8));
  await page.locator('[data-r="creature"]').click();
  const names=async()=>page.locator(".creature-card .pr-name").allTextContents().then(xs=>xs.map(x=>x.split("｜").at(-1).trim()));
  const mode=async v=>page.locator('button[data-pr-filter="mode"][data-pr-value="'+v+'"]').click();
  const chainButtonLabel=await page.locator('button[data-pr-filter="mode"][data-pr-value="familiarChain"]').textContent();
  assert.equal(chainButtonLabel,"鎖鏈魔契專屬","traditional Chinese filter label must remain readable");
  const defaultNames=await names();
  assert(defaultNames.includes("Imp"),"Warlock special Imp must appear in player default even when upstream familiar=false");
  await mode("all");
  await mode("familiarNormal");
  const regular=await names();
  for(const n of ["Cat","Crab","Vulture"])assert(regular.includes(n),"regular CR0 Beast "+n);
  for(const n of CHAIN)assert(!regular.includes(n),"chain-only form in regular "+n);
  const bat=await page.evaluate(()=>{const c=[...document.querySelectorAll(".creature-card")].find(x=>x.querySelector(".pr-name")?.textContent.endsWith("｜Bat"));return [...(c?.querySelectorAll(".pr-tags i")||[])].map(x=>x.textContent)});
  assert.equal(bat.filter(t=>t.includes("一般魔寵")).length,1,"single eligible regular tag");
  assert(!bat.some(t=>t.includes("法術：尋獲魔寵")),"no duplicate spell reference tag");
  await mode("all");
  await mode("familiarChain");
  const special=await names();
  assert.deepEqual([...special].sort(),[...CHAIN].sort(),"exact 8 Pact of the Chain special forms");
  assert(!special.includes("Cat"),"regular animal not mislabeled chain-special");
  const impTags=await page.evaluate(()=>{const c=[...document.querySelectorAll(".creature-card")].find(x=>x.querySelector(".pr-name")?.textContent.endsWith("｜Imp"));return [...(c?.querySelectorAll(".pr-tags i")||[])].map(x=>x.textContent)});
  assert(impTags.some(t=>t.includes("契術師專屬：鎖鏈魔契")));
  await mode("all");
  await mode("familiarNormal");
  await mode("familiarChain");
  const union=await names();
  assert.equal(union.length,regular.length+special.length,"pressable multi-select union");
  await mode("all");
  await mode("familiar");
  const allFam=await names();
  assert(regular.every(n=>allFam.includes(n))&&CHAIN.every(n=>allFam.includes(n)),"legacy familiar union");
  await mode("all");
  await mode("familiarNormal");
  await page.locator('button[data-pr-filter="source"][data-pr-value="all"]').click();
  assert((await names()).includes("Giant Fly"),"normal CR0 Beast can include XDMG with source filter all");
  const mobile=await browser.newPage({viewport:{width:390,height:844}});
  await mobile.goto(URL+"?qa=familiar-mobile",{waitUntil:"networkidle"});
  if(await mobile.locator("#closeRuleset").isVisible())await mobile.locator("#closeRuleset").click();
  await mobile.evaluate(()=>go(8));
  await mobile.locator('[data-r="creature"]').click();
  const m=await mobile.evaluate(()=>({overflow:document.documentElement.scrollWidth-document.documentElement.clientWidth,filters:[...document.querySelectorAll('button[data-pr-filter="mode"]')].map(x=>x.dataset.prValue)}));
  assert(m.overflow<=1,"390px mobile overflow "+m.overflow);
  assert(m.filters.includes("familiarNormal")&&m.filters.includes("familiarChain"));
  assert.deepEqual(errors,[],"browser errors");
  console.log(JSON.stringify({result:"PASS",regularCount:regular.length,chainCount:special.length,legacyCount:allFam.length,mobile:m}));
 } finally { if(browser)await browser.close(); }
})().catch(e=>{console.error(e);process.exit(1)});
