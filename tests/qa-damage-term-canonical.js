'use strict';
const assert=require('assert'),fs=require('fs'),vm=require('vm'),path=require('path');
const root=path.resolve(__dirname,'..'),read=f=>fs.readFileSync(path.join(root,f),'utf8');
const index=read('index.html'),full=read('assets/data/spell-rules-2024.js'),spell=read('assets/data/spells-phb-2024.js'),legacy=read('assets/data/spells-phb-2014.json'),generator=read('scripts/build-5r-spell-rules.py');
const expected=['酸蝕','鈍擊','寒冷','火焰','力場','閃電','黯蝕','穿刺','毒素','心靈','光耀','揮砍','雷鳴'];
const found=index.match(/const CLASS_DAMAGE_TYPES_2024=\[([^\]]+)\]/);
assert(found,'2024 damage table missing');
assert.deepStrictEqual(JSON.parse('['+found[1]+']'),expected,'Must preserve 13 canonical types');
assert(!full.includes('暗蝕'), 'Full rules retain simplified necrotic name');
assert(!full.includes('強酸傷害')&&!full.includes('強酸，寒冷')&&!full.includes('強酸、寒冷'),'Full rules retain acid damage alias');
assert(full.includes('一灘強酸'),'Physical acid narration must survive');
assert(full.includes('強酸中泡澡'),'Physical acid in memory spell must survive');
assert(!index.includes('死靈傷害')&&!legacy.includes('死靈傷害'),'Explicit 2014 damage type should be 黯蝕');
assert(index.includes('死靈學派'),'Necromancy school must survive');
assert(index.includes('馬友夫強酸箭'),'Named spell must survive');
assert(spell.includes('4d4 酸蝕傷害'),'2024 spell summary must use Acid type');
assert(generator.includes('__ACID_MATERIAL__'),'Future regeneration must preserve physical acid');
const sandbox={globalThis:{}};vm.runInNewContext(full,sandbox);
const rules=sandbox.globalThis.SPELLS_2024_FULL_RULES;
assert.equal(Object.keys(rules).length,391,'Full 2024 spell count must remain 391');
for(const [key,rule] of Object.entries(rules))assert(!/強酸傷害|暗蝕|死靈傷害|光輝傷害/.test(rule),'Damage alias in '+key);
JSON.parse(legacy);
console.log(JSON.stringify({pass:true,types:expected.length,fullRules:Object.keys(rules).length,physicalAcidPreserved:true,legacy2014Parsed:true}));
