"use strict";
const assert=require("node:assert/strict");
require(process.cwd()+"/assets/data/spells-phb-2024.js");
require(process.cwd()+"/assets/data/spell-rules-2024.js");
require(process.cwd()+"/assets/spell-quick-facts-2024.js");
const rows=globalThis.SPELLS_2024_TUPLES;
const fmt=globalThis.ZIZI_5R_SPELL_QUICK_FACTS_2024;
assert.equal(typeof fmt,"function");
assert.equal(rows.length,391);
const spell=en=>{const r=rows.find(row=>row[2]===en);assert(r,"Missing "+en);return {identifier:r[0]};};
const find=(en,lv=3)=>fmt(spell(en),lv);
function check(en,{dice="",save="",attack="",noDamage=false,lv=3}){
 const v=find(en,lv);
 if(dice)assert(v.damage.includes(dice),en+" missing "+dice+": "+JSON.stringify(v));
 if(save)assert(v.save.includes(save),en+" missing "+save+": "+JSON.stringify(v));
 if(attack)assert.equal(v.attack,attack,en+" attack");
 if(noDamage)assert.equal(v.damage,"",en+" falsely labeled damage");
 console.log(en,JSON.stringify(v));
}
check("Poison Spray",{dice:"1d12",attack:"\u6cd5\u8853\u653b\u64ca"});
check("Poison Spray",{dice:"2d12",lv:5});
check("Poison Spray",{dice:"3d12",lv:11});
check("Hail of Thorns",{dice:"1d10",save:"\u654f\u6377"});
check("Hunter's Mark",{dice:"1d6"});
assert(find("Hunter's Mark").damage.startsWith("\u547d\u4e2d\u984d\u5916"),"Hunter's Mark is bonus damage on a hit");
check("Animal Friendship",{save:"\u611f\u77e5",noDamage:true});
check("Alarm",{noDamage:true});
check("Bless",{noDamage:true});
check("Guidance",{noDamage:true});
check("Haste",{noDamage:true});
assert.equal(find("Beacon of Hope").save,"","Beacon of Hope grants advantage; it does not force a saving throw");
check("Beacon of Hope",{noDamage:true});
check("Fireball",{dice:"8d6",save:"\u654f\u6377"});
check("Magic Missile",{dice:"1d4+1"});
for(const [lv,die] of [[1,"1d8"],[4,"1d8"],[5,"1d10"],[11,"1d12"],[17,"2d6"]]){
 const d=find("Shillelagh",lv).damage;
 assert(d.startsWith(die+"＋施法屬性調整值"),"Shillelagh damage formula at "+lv+": "+d);
 assert(d.includes("鈍擊／力場"),"Shillelagh damage type choice at "+lv+": "+d);
}
check("Shillelagh",{dice:"1d10",lv:5});
check("True Strike",{dice:"1d6",lv:5});
check("Spirit Guardians",{dice:"3d8",save:"\u611f\u77e5"});
assert(find("Spirit Guardians").damage.includes("\u9eef\u8755"),"Spirit Guardians radiant/necrotic choice");
check("Toll the Dead",{dice:"2d8",lv:5,save:"\u611f\u77e5"});
check("Witch Bolt",{dice:"2d12",attack:"\u6cd5\u8853\u653b\u64ca"});
check("Armor of Agathys",{dice:"5"});
const all=rows.map(row=>[row[2],fmt({identifier:row[0]},7)]);
assert(all.every(([,f])=>f&&Object.values(f).every(v=>typeof v==="string"&&!/undefined|NaN/.test(v))));
const results={total:rows.length,damage:all.filter(([,f])=>f.damage).length,save:all.filter(([,f])=>f.save).length,attack:all.filter(([,f])=>f.attack).length};
