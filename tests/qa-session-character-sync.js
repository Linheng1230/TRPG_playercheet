const assert=require('node:assert/strict');
const C=require('../assets/session-character-sync.js');
const store=new Map();const storage={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v)};
const original={v:9,id:'c12345',cls:'德魯伊',level:4,play:{hp:22,hpMax:30,thp:0,res:{}},slotsUsed:{l1:1},sessionResourceLimits:{slots:{l1:4},classes:{ws:{label:'荒野變身',max:2}}},meta:{name:'奈瑟林'},base:{wis:16}};
storage.setItem('dnd5r:char:c12345',JSON.stringify(original));
assert.equal(C.read(storage,'c12345').play.hp,22);
C.update(storage,'c12345',{kind:'hp',value:17});
C.update(storage,'c12345',{kind:'temp',value:5});
C.update(storage,'c12345',{kind:'slot',key:'l1',used:2});
C.update(storage,'c12345',{kind:'resource',key:'ws',used:1});
const saved=C.read(storage,'c12345');assert.equal(saved.play.hp,17);assert.equal(saved.play.thp,5);assert.equal(saved.slotsUsed.l1,2);assert.equal(saved.play.res.ws,1);assert.deepEqual(saved.base,original.base);assert.equal(saved.meta.name,'奈瑟林');
