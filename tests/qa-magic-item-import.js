"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,".."),read=p=>fs.readFileSync(path.join(root,p),"utf8"),html=read("index.html"),ref=read("assets/player-reference-5r.js"),pdf=read("assets/character-sheet-export.js"),xlsx=read("assets/character-sheet-xlsx-export.js");
assert(html.includes('assets/magic-item-import-5r.js'),"Import module missing from page");
for(const kind of ["weapon","armor","equipment"])assert(html.includes('MagicItemImport5R?.render(S,"'+kind+'")'),"Final sheet missing "+kind);
assert(html.includes('MagicItemImport5R?.normalize(S.gear.magicItems)'),"Legacy deserialization missing");
assert(html.includes('gear:JSON.parse(JSON.stringify(S.gear))'),"Save serialization must include inventory");
assert(html.includes('魔法物品:window.MagicItemImport5R?.readable(S)'),"Readable JSON missing");
assert(pdf.includes("MagicItemImport5R?.equipmentText(S)"),"PDF export missing");
assert(xlsx.includes("MagicItemImport5R?.weaponRows(S)")&&xlsx.includes("MagicItemImport5R?.readable(S)"),"Workbook export missing");
assert(ref.includes('MagicItemImport5R?.actionHTML(S,x)'),"435 item actions missing");
const noop=()=>{},doc={addEventListener:noop,getElementById:()=>null,querySelectorAll:()=>[],createElement:()=>({textContent:""}),head:{appendChild:noop}};
const cx={window:{addEventListener:noop},document:doc,S:{cls:{n:"戰士"},step:8,gear:{weapons:[],magicItems:[]}},escFeatureHTML:s=>String(s),toast:noop,autoSave:noop,update:noop,renderFinal:noop,setTimeout:noop,location:{search:""},URLSearchParams};
vm.createContext(cx);
vm.runInContext(read("assets/data/magic-items-5r.js"),cx);
vm.runInContext(read("assets/magic-item-import-5r.js"),cx);
vm.runInContext(ref,cx);
const api=cx.window.MagicItemImport5R,all=cx.window.ZIZI_5R_MAGIC_ITEMS;
assert.equal(all.length,435);assert.equal(new Set(all.map(x=>x.id)).size,435);
const rendered=vm.runInContext("renderMagicItemRef()",cx);
assert.equal((rendered.match(/data-magic-add=/g)||[]).length,435,"435 buttons");
const weapon=all.find(x=>x.type==="M"),armor=all.find(x=>["LA","MA","HA","S"].includes(x.type)),other=all.find(x=>x.type==="P");
for(const x of [weapon,armor,other])assert(api.add(cx.S,x.id).ok);
assert.deepEqual(Array.from(api.rows(cx.S),r=>r.group),["weapon","armor","equipment"]);
assert.equal(api.readable(cx.S).length,3);
assert(api.render(cx.S,"weapon").includes("pr-magic-owned"));
assert(api.equipmentText(cx.S).includes("魔法武器"));
assert.equal(api.weaponRows(cx.S).length,1);
assert(api.add(cx.S,other.id).ok);assert.equal(api.rows(cx.S).find(r=>r.id===other.id).qty,2);
const saved=JSON.parse(JSON.stringify(cx.S.gear)),loaded={gear:{magicItems:api.normalize(saved.magicItems)}};
assert.equal(api.rows(loaded).length,3,"Save/load roundtrip");
assert(api.remove(loaded,other.id));assert.equal(api.rows(loaded).find(r=>r.id===other.id).qty,1);
const empty={gear:{magicItems:[]}};assert(!api.add(empty,other.id).ok);assert.equal(api.rows(empty).length,0);
assert.equal(api.normalize([{id:"legacy-missing",qty:2}]).length,1,"Unknown IDs must survive migration");
assert(read("assets/magic-item-import-5r.js").includes("@media(max-width:520px)"),"Mobile layout missing");
console.log("PASS 435 magic item import actions, routing, roundtrip, quantities, remove, JSON/PDF/XLSX, mobile styling");
